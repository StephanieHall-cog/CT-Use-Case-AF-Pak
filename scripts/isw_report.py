"""Regenerate the map inventory table at the end of docs/isw-maps.md from db/afpak.sqlite."""
import os, re, sqlite3
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
con = sqlite3.connect(f"{ROOT}/db/afpak.sqlite")
rows = con.execute("""SELECT m.id, m.title, coalesce(m.period_start,''), coalesce(m.period_end, m.as_of_date, ''), m.page_date, m.map_type, m.n_plots,
  (SELECT count(*) FROM map_plots p WHERE p.map_id=m.id AND p.lat IS NOT NULL), m.n_anchors_used, m.georef_rms_km, m.url FROM map_sources m
  ORDER BY coalesce(m.period_end, m.as_of_date, m.page_date)""").fetchall()
lines = ["| Map | Period | Published | Type | Plots (geocoded) | Anchors used | Fit RMS km |", "|---|---|---|---|---|---|---|"]
for r in rows:
    per = f"{r[2]} → {r[3]}" if r[2] else r[3]
    lines.append(f"| [{r[1]}]({r[10]}) | {per} | {r[4] or ''} | {r[5] or ''} | {r[6]} ({r[7]}) | {r[8]} | {r[9] if r[9] is not None else '—'} |")
tot = con.execute("SELECT count(*), sum(lat IS NOT NULL) FROM map_plots").fetchone()
lines.append(f"\n**{len(rows)} maps · {tot[0]} plots · {tot[1]} geocoded** · map_text rows: {con.execute('SELECT count(*) FROM map_text').fetchone()[0]} · place_coords: {con.execute('SELECT count(*) FROM place_coords').fetchone()[0]}")
by = con.execute("SELECT event_type, count(*) FROM map_plots GROUP BY 1 ORDER BY 2 DESC").fetchall()
lines.append("\nPlots by event_type: " + ", ".join(f"{a} {b}" for a, b in by))
p = f"{ROOT}/docs/isw-maps.md"; s = open(p).read()
s = s[: s.index("(generated by `python3 scripts/isw_report.py`)") + len("(generated by `python3 scripts/isw_report.py`)")] + "\n\n" + "\n".join(lines) + "\n"
open(p, "w").write(s); print("\n".join(lines[-2:]))
